#include "fractol.h"

int	frt_is_digit(char c)
{
	return (c >= '0' && c <= '9');
}

int	frt_str_are_eq(char *s1, char *s2)
{
	int	i;

	if (!s1 || !s2)
		return (0);
	i = 0;
	while (s1[i] && s2[i] && (s1[i] == s2[i]))
		i++;
	return (s1[i] == '\0' && s2[i] == '\0');
}
